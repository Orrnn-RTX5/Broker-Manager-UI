#!/bin/sh
set -eu

runtime_file="${NGINX_HTML_DIR:-/usr/share/nginx/html}/runtime-config.js"

BACKEND_TARGET_VALUE="${BACKEND_TARGET:-${VITE_BACKEND_TARGET:-${BACKEND_MODE:-${VITE_BACKEND_MODE:-web}}}}"
API_HOST_VALUE="${API_HOST:-${VITE_API_HOST:-}}"
API_HOST_EXT_VALUE="${API_HOST_EXT:-${VITE_API_HOST_EXT:-}}"
WS_HOST_VALUE="${WS_HOST:-${VITE_WS_HOST:-}}"
WS_FEED_PATH_VALUE="${WS_FEED_PATH:-${VITE_WS_FEED_PATH:-/ws/feed}}"
FEED_BROKER_ID_VALUE="${FEED_BROKER_ID:-${VITE_FEED_BROKER_ID:-${BROKER_ID:-${VITE_BROKER_ID:-}}}}"
DEFAULT_MT5_SERVER_VALUE="${DEFAULT_MT5_SERVER:-${VITE_DEFAULT_MT5_SERVER:-}}"
DISCOVERY_BASE_URL_VALUE="${DISCOVERY_BASE_URL:-${VITE_DISCOVERY_BASE_URL:-}}"
USE_MOCK_DISCOVERY_VALUE="${USE_MOCK_DISCOVERY:-${VITE_USE_MOCK_DISCOVERY:-false}}"

[ -z "$DISCOVERY_BASE_URL_VALUE" ] && echo 'WARNING: DISCOVERY_BASE_URL is not configured; broker discovery will fail visibly at runtime.' >&2
GROUP_OPERATIONS_BROKERS_VALUE="${GROUP_OPERATIONS_BROKERS-${VITE_GROUP_OPERATIONS_BROKERS:-}}"
BROKER_ID_VALUE="${BROKER_ID-${VITE_BROKER_ID-$FEED_BROKER_ID_VALUE}}"
MANAGER_WS_HOST_VALUE="${MANAGER_WS_HOST-${VITE_MANAGER_WS_HOST-}}"
MARKET_DATA_SOURCE_VALUE="${MARKET_DATA_SOURCE-${VITE_MARKET_DATA_SOURCE-bridge}}"
MANAGER_PROXY_STRIP_MANAGER_PREFIX_VALUE="${MANAGER_PROXY_STRIP_MANAGER_PREFIX-${VITE_MANAGER_PROXY_STRIP_MANAGER_PREFIX-false}}"
POSITION_UPDATES_WS_PATH_VALUE="${POSITION_UPDATES_WS_PATH-${VITE_POSITION_UPDATES_WS_PATH-}}"
FEED_WS_URL_VALUE="${FEED_WS_URL-${VITE_FEED_WS_URL-}}"
FEED_STATUS_URL_VALUE="${FEED_STATUS_URL-${VITE_FEED_STATUS_URL-}}"

json_escape() {
  printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

cat > "$runtime_file" <<EOF
window.__RTX_RUNTIME_CONFIG__ = {
  CONFIG_SOURCE: "deployment",
  BROKER_ID: "$(json_escape "$BROKER_ID_VALUE")",
  MANAGER_WS_HOST: "$(json_escape "$MANAGER_WS_HOST_VALUE")",
  MARKET_DATA_SOURCE: "$(json_escape "$MARKET_DATA_SOURCE_VALUE")",
  MANAGER_PROXY_STRIP_MANAGER_PREFIX: "$(json_escape "$MANAGER_PROXY_STRIP_MANAGER_PREFIX_VALUE")",
  POSITION_UPDATES_WS_PATH: "$(json_escape "$POSITION_UPDATES_WS_PATH_VALUE")",
  FEED_WS_URL: "$(json_escape "$FEED_WS_URL_VALUE")",
  FEED_STATUS_URL: "$(json_escape "$FEED_STATUS_URL_VALUE")",
  BACKEND_TARGET: "$(json_escape "$BACKEND_TARGET_VALUE")",
  API_HOST: "$(json_escape "$API_HOST_VALUE")",
  WS_HOST: "$(json_escape "$WS_HOST_VALUE")",
  WS_FEED_PATH: "$(json_escape "$WS_FEED_PATH_VALUE")",
  FEED_BROKER_ID: "$(json_escape "$FEED_BROKER_ID_VALUE")",
  API_HOST_EXT: "$(json_escape "$API_HOST_EXT_VALUE")",
  DEFAULT_MT5_SERVER: "$(json_escape "$DEFAULT_MT5_SERVER_VALUE")",
  DISCOVERY_BASE_URL: "$(json_escape "$DISCOVERY_BASE_URL_VALUE")",
  USE_MOCK_DISCOVERY: "$(json_escape "$USE_MOCK_DISCOVERY_VALUE")",
  GROUP_OPERATIONS_BROKERS: "$(json_escape "$GROUP_OPERATIONS_BROKERS_VALUE")"
};
window.RUNTIME_CONFIG = window.__RTX_RUNTIME_CONFIG__;
EOF

exec "$@"
